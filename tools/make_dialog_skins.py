    SKIN.mkdir(parents=True, exist_ok=True)
    written = []

    # ok.xml -------------------------------------------------------------
    body = "\n".join([textbox(3010, 32, 104, 656, 150), button(10, 470, 276, 218, "OK")])
    written.append(write("ok.xml", shell(720, 360, body), 10))

