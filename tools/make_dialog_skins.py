"""Generate the dialog skin XML files.

They share a panel, header, accent rule and button styling, so they are
generated from one template rather than five hand-maintained copies that drift.
Run after changing the look:

    py -3 tools/make_dialog_skins.py
"""
import sys
from pathlib import Path

SKIN = Path(__file__).resolve().parents[1] / "plugin.video.grnshows/resources/skins/Default/1080i"

ACCENT = "FF34D399"
PANEL = "F81B1D22"
HEADER = "FF12141A"
TEXT = "FFD2D6DC"
MUTED = "FF8A8F9A"


def shell(width, height, body, heading_font="font14"):
    """Dim background, centred panel, header bar, accent rule, then body."""
    x, y = (1920 - width) // 2, (1080 - height) // 2
    return """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/make_dialog_skins.py. Edit that, not this file. -->
<window>
  <defaultcontrol always="true">%(default)s</defaultcontrol>
  <coordinates><system>1</system><posx>0</posx><posy>0</posy></coordinates>
  <controls>
    <control type="image">
      <posx>0</posx><posy>0</posy><width>1920</width><height>1080</height>
      <texture>DialogBack.png</texture><colordiffuse>D8000000</colordiffuse>
    </control>
    <control type="group">
      <posx>%(x)s</posx><posy>%(y)s</posy>
      <control type="image">
        <posx>0</posx><posy>0</posy><width>%(w)s</width><height>%(h)s</height>
        <texture border="2">white.png</texture><colordiffuse>%(panel)s</colordiffuse>
      </control>
      <control type="image">
        <posx>0</posx><posy>0</posy><width>%(w)s</width><height>78</height>
        <texture border="2">white.png</texture><colordiffuse>%(header)s</colordiffuse>
      </control>
      <control type="label" id="3000">
        <posx>32</posx><posy>18</posy><width>%(hw)s</width><height>42</height>
        <font>%(hf)s</font><textcolor>FFFFFFFF</textcolor><label></label>
      </control>
      <control type="image">
        <posx>0</posx><posy>78</posy><width>%(w)s</width><height>2</height>
        <texture>white.png</texture><colordiffuse>%(accent)s</colordiffuse>
      </control>
%(body)s
    </control>
  </controls>
</window>
""" % {"x": x, "y": y, "w": width, "h": height, "hw": width - 64, "hf": heading_font,
       "panel": PANEL, "header": HEADER, "accent": ACCENT, "body": body,
       "default": BODY_DEFAULT.get(id(body), 10)}


BODY_DEFAULT = {}


def button(control_id, x, y, width, label, on_left=None, on_right=None):
    nav = ""
    if on_left:
        nav += "<onleft>%s</onleft>" % on_left
    if on_right:
        nav += "<onright>%s</onright>" % on_right
    return """      <control type="button" id="%(id)s">
        <posx>%(x)s</posx><posy>%(y)s</posy><width>%(w)s</width><height>56</height>
        <font>font13</font><align>center</align><aligny>center</aligny>
        <textcolor>%(text)s</textcolor><focusedcolor>FF12141A</focusedcolor>
        <texturefocus border="2" colordiffuse="%(accent)s">white.png</texturefocus>
        <texturenofocus border="2" colordiffuse="22FFFFFF">white.png</texturenofocus>
        <label>%(label)s</label>%(nav)s
      </control>""" % {"id": control_id, "x": x, "y": y, "w": width, "label": label,
                       "text": TEXT, "accent": ACCENT, "nav": nav}


def textbox(control_id, x, y, width, height, font="font13", colour=TEXT):
    return """      <control type="textbox" id="%s">
        <posx>%s</posx><posy>%s</posy><width>%s</width><height>%s</height>
        <font>%s</font><textcolor>%s</textcolor><label></label>
      </control>""" % (control_id, x, y, width, height, font, colour)


def write(name, xml, default_control):
    xml = xml.replace("<defaultcontrol always=\"true\">10</defaultcontrol>",
                      "<defaultcontrol always=\"true\">%s</defaultcontrol>" % default_control)
    path = SKIN / name
    path.write_text(xml, encoding="utf-8", newline="\n")
    return path


